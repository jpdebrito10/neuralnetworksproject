"""# Estabelecimento do Autencoder e Treinamento"""

import tensorflow as tf
from tensorflow.keras.models import Model
from tensorflow.keras.layers import Input, Dense
from tensorflow.keras.callbacks import EarlyStopping, ModelCheckpoint

# Reprodutibilidade dos resultados
SEED = 42

np.random.seed(SEED)
tf.random.set_seed(SEED)


# Arquitetura escolhida:
# 7 → 4 → 2 → 4 → 7

# Camada de entrada
entrada = Input(
    shape=(7,),
    name="entrada"
)

# ENCODER
encoder_1 = Dense(
    units=4,
    activation="relu",
    name="encoder_4"
)(entrada)

espaco_latente = Dense(
    units=2,
    activation="linear",
    name="latent_space"
)(encoder_1)

# DECODER
decoder_1 = Dense(
    units=4,
    activation="relu",
    name="decoder_4"
)(espaco_latente)

saida = Dense(
    units=7,
    activation="sigmoid",
    name="saida"
)(decoder_1)

# CRIAÇÃO DO MODELO
autoencoder = Model(
    inputs=entrada,
    outputs=saida,
    name="Autoencoder_7_4_2_4_7"
)


#autoencoder.summary()

# COMPILAÇÃO
autoencoder.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001), loss="mse")

# EarlyStopping:
early_stopping = EarlyStopping(
    monitor="val_loss",
    patience=10,
    min_delta=0.0001,
    restore_best_weights=True,
    verbose=1
)

# SALVAR MELHOR MODELO
checkpoint = ModelCheckpoint(
    filepath="melhor_autoencoder.keras",
    monitor="val_loss",
    save_best_only=True,
    verbose=0
)

# TREINAMENTO
history = autoencoder.fit(
    X_train,
    X_train,
    validation_data=(X_val, X_val),
    epochs=50,
    batch_size=256,
    shuffle=True,
    callbacks=[early_stopping, checkpoint],
    verbose=1
)

print("\nTreinamento concluído.")

# HISTÓRICO DE TREINAMENTO
np.save("loss_treinamento.npy", history.history["loss"])
np.save("loss_validacao.npy", history.history["val_loss"])

print("Última val_loss:", history.history['val_loss'][-1])
print("Última loss:", history.history['loss'][-1])

