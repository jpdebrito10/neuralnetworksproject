"""# Validação Cruzada"""

from sklearn.model_selection import TimeSeriesSplit

X_dev_completo = np.vstack((X_train, X_val))
X_dev = X_dev_completo[::5]

n_splits = 5
tscv = TimeSeriesSplit(n_splits=n_splits)
fold_val_losses = []

print(f"Iniciando Validação Cruzada Temporal com volume reduzido (20%)")
print(f"Volume original: {X_dev_completo.shape[0]} | Novo volume reduzido: {X_dev.shape[0]}")

def construir_autoencoder():
    entrada = Input(shape=(7,), name="entrada")
    encoder_1 = Dense(units=4, activation="relu", name="encoder_4")(entrada)
    espaco_latente = Dense(units=2, activation="relu", name="latent_space")(encoder_1)
    decoder_1 = Dense(units=4, activation="relu", name="decoder_4")(espaco_latente)
    saida = Dense(units=7, activation="sigmoid", name="saida")(decoder_1)

    modelo = Model(inputs=entrada, outputs=saida)
    modelo.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001), loss="mse")
    return modelo

for fold, (train_index, val_index) in enumerate(tscv.split(X_dev), 1):
    print("\n")
    print(f"TREINANDO O FOLD {fold}/{n_splits}")
    print(f"Treino: {len(train_index)} amostras")
    print(f"Validação: {len(val_index)} amostras")

    X_train_fold = X_dev[train_index]
    X_val_fold = X_dev[val_index]

    tf.keras.backend.clear_session()
    tf.random.set_seed(SEED)
    model_fold = construir_autoencoder()

    early_stopping_fold = EarlyStopping(
        monitor="val_loss",
        patience=10,
        min_delta=0.0001,
        restore_best_weights=True,
        verbose=0
    )
    history_fold = model_fold.fit(
        X_train_fold, X_train_fold,
        validation_data=(X_val_fold, X_val_fold),
        epochs=50,
        batch_size=256,
        shuffle=True,
        callbacks=[early_stopping_fold],
        verbose=0
    )

    melhor_val_loss = min(history_fold.history['val_loss'])
    fold_val_losses.append(melhor_val_loss)
    print(f"Melhor val_loss (MSE): {melhor_val_loss:.6f}")

# RESUMO DOS RESULTADOS
print("\nResumo da Validação Cruzada")
media_loss = np.mean(fold_val_losses)
desvio_loss = np.std(fold_val_losses)

print(f"Média do MSE de Validação: {media_loss:.6f}")
print(f"Desvio Padrão do MSE:      {desvio_loss:.6f}")

